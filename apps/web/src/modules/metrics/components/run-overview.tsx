"use client";

import type { RunSnapshot, SampleStatistics } from "@rectangles/engine";
import { useMemo } from "react";
import { useRunStore } from "@/modules/simulation";
import { InfoTip } from "@/components/info-tip";
import type { RunTiming } from "../lib/window-readings";
import { latencyChart, trafficRateChart } from "../lib/chart-series";
import { overviewFigures } from "../lib/overview-figures";
import { formatMetricValue, formatNumber, formatPercentage, formatPercentiles, formatPerSecond, NO_VALUE } from "../lib/format-metric";
import { MetricChart } from "./metric-chart";

/** What each whole-system figure means. Shown on hover, word for word. */
const DEFINITIONS = {
  offered: "Requests generated by clients per second, including retries.",
  throughput: "Requests answered successfully within the client's timeout, per second.",
  latency:
    "Time from a client sending a request to receiving its successful answer. p95 means 95% of requests were at least this fast.",
  errors: "Requests that were rejected, failed or timed out, as a share of requests offered.",
} as const;

function Tile({
  name,
  definition,
  value,
  detail,
}: {
  name: string;
  definition: string;
  value: string;
  detail?: string | undefined;
}) {
  return (
    <div className="min-w-0 rounded-lg border p-3" data-slot="run-tile" data-metric={name}>
      <div className="flex items-center gap-1.5 text-xs text-muted-foreground">
        {name}
        <InfoTip label={`What ${name} means`}>{definition}</InfoTip>
      </div>
      <div className="mt-1 truncate text-lg leading-6 font-medium tabular-nums">{value}</div>
      {detail !== undefined && (
        <div className="truncate text-xs text-muted-foreground tabular-nums" title={detail}>
          {detail}
        </div>
      )}
    </div>
  );
}

function latencyDetail(latency: SampleStatistics | null): string | undefined {
  return latency === null || latency.count === 0
    ? undefined
    : formatPercentiles(latency, "ms", ["p95", "p99"]);
}

/**
 * The whole system's figures. During a run they cover the latest complete second;
 * once it ends they cover the whole run, with exact percentiles.
 */
export function RunOverview({ metrics, timing }: { metrics: RunSnapshot; timing: RunTiming }) {
  const result = useRunStore((state) => state.result);
  const { summary } = metrics;
  const { windowSeconds, isLive } = timing;
  const figures = overviewFigures(summary, result?.summary.latencyMs ?? null, windowSeconds, isLive);
  const latency = figures.latencyMs;

  const trafficChart = useMemo(
    () => trafficRateChart(summary.windows, windowSeconds, isLive),
    [summary.windows, windowSeconds, isLive],
  );
  const latencyOverTime = useMemo(
    () => latencyChart(summary.windows, windowSeconds, isLive),
    [summary.windows, windowSeconds, isLive],
  );

  return (
    <div className="grid gap-4 p-4">
      <p className="text-xs text-muted-foreground">{figures.scope}</p>
      <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
        <Tile name="Offered" definition={DEFINITIONS.offered} value={formatPerSecond(figures.offeredPerSecond, "requests")} />
        <Tile
          name="Throughput"
          definition={DEFINITIONS.throughput}
          value={formatPerSecond(figures.throughputPerSecond, "requests")}
        />
        <Tile
          name="Latency p50"
          definition={DEFINITIONS.latency}
          value={latency === null || latency.count === 0 ? NO_VALUE : formatMetricValue(latency.p50, "ms")}
          detail={latencyDetail(latency)}
        />
        <Tile
          name="Errors"
          definition={DEFINITIONS.errors}
          value={figures.errorRate === null ? NO_VALUE : formatPercentage(figures.errorRate)}
          detail={`rejected ${formatNumber(summary.rejected)} · failed ${formatNumber(summary.failed)} · timed out ${formatNumber(summary.timedOut)}`}
        />
      </div>
      <div className="grid gap-4 lg:grid-cols-2">
        <div className="min-w-0">
          <h3 className="mb-1 text-xs font-medium">Requests per second</h3>
          <MetricChart chart={trafficChart} label="Offered, successful and failed requests per second over the run" />
        </div>
        <div className="min-w-0">
          <h3 className="mb-1 text-xs font-medium">Latency (ms)</h3>
          <MetricChart chart={latencyOverTime} label="Latency percentiles of successful requests over the run" />
        </div>
      </div>
    </div>
  );
}
